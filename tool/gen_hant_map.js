// Generates lib/core/zh_hant_map.dart from Windows' built-in
// Simplified -> Traditional table, plus Taiwan software vocabulary overrides.
// Build-time helper only; the app itself has no new dependency.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const chars = new Set();
function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) walk(full);
    else if (name.endsWith('.dart')) {
      for (const ch of fs.readFileSync(full, 'utf8')) {
        if (/[\u4e00-\u9fff]/.test(ch)) chars.add(ch);
      }
    }
  }
}
walk(path.join(root, 'lib'));

const input = [...chars].sort();
const inPath = 'C:\\hant_in.json';
const outPath = 'C:\\hant_out.json';
fs.writeFileSync(inPath, JSON.stringify(input), 'utf8');

const ps = `
Add-Type -AssemblyName Microsoft.VisualBasic
$chars = Get-Content -Raw -Encoding UTF8 '${inPath}' | ConvertFrom-Json
$out = @{}
foreach ($ch in $chars) {
  $t = [Microsoft.VisualBasic.Strings]::StrConv([string]$ch, [Microsoft.VisualBasic.VbStrConv]::TraditionalChinese, 0)
  if ($t -ne $ch) { $out[$ch] = $t }
}
$json = $out | ConvertTo-Json -Compress
[System.IO.File]::WriteAllText('${outPath}', $json, (New-Object System.Text.UTF8Encoding($false)))
`;
const psPath = 'C:\\hant.ps1';
fs.writeFileSync(psPath, ps, 'ascii');
execFileSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', psPath]);
const pairs = JSON.parse(fs.readFileSync(outPath, 'utf8'));


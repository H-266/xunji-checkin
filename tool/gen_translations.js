const fs = require('fs');

function read(name) {
  const p = `tool/tr_${name}.json`;
  if (!fs.existsSync(p)) return {};
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

const langs = ['en', 'ja', 'fr', 'es'];
const data = Object.fromEntries(langs.map((l) => [l, read(l)]));
const allKeys = [...new Set(langs.flatMap((l) => Object.keys(data[l])))].sort();

function dartMap(name, map) {
  const entries = allKeys
    .filter((k) => typeof map[k] === 'string' && map[k].trim())
    .map((k) => `  ${JSON.stringify(k).replace(/\$/g, '\\$')}: ${JSON.stringify(map[k]).replace(/\$/g, '\\$')},`)
    .join('\n');
  return `const Map<String, String> ${name} = <String, String>{\n${entries}\n};\n`;
}

const header = `// GENERATED by tool/gen_translations.js. Do not edit by hand.\n`;
let out = header;
out += dartMap('generatedEn', data.en);
out += '\n' + dartMap('generatedJa', data.ja);
out += '\n' + dartMap('generatedFr', data.fr);
out += '\n' + dartMap('generatedEs', data.es);
fs.writeFileSync('lib/core/app_strings_generated.dart', out, 'utf8');
console.log('keys', allKeys.length, 'sizes', langs.map((l) => `${l}:${Object.keys(data[l]).length}`).join(' '));
